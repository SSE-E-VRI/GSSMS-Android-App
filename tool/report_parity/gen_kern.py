"""Extract Segoe UI GPOS 'kern' pair adjustments for printable ASCII (+ a few
punctuation code points used by the reports) and write a Dart const file.
Usage: py tool/report_parity/gen_kern.py lib/features/work_orders/services/report_pdf/segoe_kerning.dart (needs the Windows Segoe UI fonts + fontTools)
"""
import sys
from fontTools.ttLib import TTFont

FONTS = {
    'regular': 'C:/Windows/Fonts/segoeui.ttf',
    'semibold': 'C:/Windows/Fonts/seguisb.ttf',
    'bold': 'C:/Windows/Fonts/segoeuib.ttf',
}
CODES = [chr(c) for c in range(0x21, 0x7F)] + ['\u2019', '\u2018', '\u201c', '\u201d', '\u2013', '\u2014', '\u2026', '\u00b7']


def kern_table(path):
    f = TTFont(path)
    cmap = f.getBestCmap()
    upm = f['head'].unitsPerEm
    gpos = f['GPOS'].table
    feats = [fr for fr in gpos.FeatureList.FeatureRecord if fr.FeatureTag == 'kern']
    lookup_idx = []
    # Features reachable from DFLT/latn default language systems
    scripts = {sr.ScriptTag: sr.Script for sr in gpos.ScriptList.ScriptRecord}
    wanted = set()
    for tag in ('latn', 'DFLT'):
        sc = scripts.get(tag)
        if not sc:
            continue
        langs = [sc.DefaultLangSys] if sc.DefaultLangSys else []
        for lr in sc.LangSysRecord:
            if lr.LangSysTag in ('ENG ', 'IND ', 'TAM '):
                pass
        for ls in langs:
            for fi in ls.FeatureIndex:
                if gpos.FeatureList.FeatureRecord[fi].FeatureTag == 'kern':
                    wanted.add(fi)
    for fi in sorted(wanted):
        for li in gpos.FeatureList.FeatureRecord[fi].Feature.LookupListIndex:
            if li not in lookup_idx:
                lookup_idx.append(li)
    lookup_idx.sort()

    def pair_value(g1, g2):
        total = 0
        for li in lookup_idx:
            lk = gpos.LookupList.Lookup[li]
            for st in lk.SubTable:
                if lk.LookupType == 9:
                    st = st.ExtSubTable
                if st.LookupType if hasattr(st, 'LookupType') else None:
                    pass
                if not hasattr(st, 'Coverage') or not hasattr(st, 'Format'):
                    continue
                if st.__class__.__name__ != 'PairPos':
                    continue
                cov = st.Coverage.glyphs
                if g1 not in cov:
                    continue
                if st.Format == 1:
                    ps = st.PairSet[cov.index(g1)]
                    hit = None
                    for pvr in ps.PairValueRecord:
                        if pvr.SecondGlyph == g2:
                            hit = pvr
                            break
                    if hit is None:
                        continue
                    v = hit.Value1.XAdvance if hit.Value1 and hasattr(hit.Value1, 'XAdvance') else 0
                    total += v or 0
                    break
                else:
                    c1 = st.ClassDef1.classDefs.get(g1, 0)
                    c2 = st.ClassDef2.classDefs.get(g2, 0)
                    rec = st.Class1Record[c1].Class2Record[c2]
                    v = rec.Value1.XAdvance if rec.Value1 and hasattr(rec.Value1, 'XAdvance') else 0
                    if v:
                        total += v
                        break
                    # class pair without value: lookup still "matched" per spec
                    break
        return total

    out = {}
    glyphs = {ch: cmap[ord(ch)] for ch in CODES if ord(ch) in cmap}
    for a, ga in glyphs.items():
        for b, gb in glyphs.items():
            v = pair_value(ga, gb)
            if v:
                out[a + b] = round(v * 2048 / upm)
    return out


def dart_str(s):
    r = s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
    return "'" + r + "'"


def main():
    out_path = sys.argv[1]
    lines = []
    lines.append('// GENERATED by tool/report_parity/gen_kern.py from the Segoe UI GPOS `kern`')
    lines.append('// feature: pair adjustments in 1/2048 em for printable ASCII and the report')
    lines.append('// punctuation. Chrome applies them; the pdf package does not.')
    lines.append('')
    for name, path in FONTS.items():
        t = kern_table(path)
        lines.append(f'/// Segoe UI {name} pair kerning (1/2048 em).')
        lines.append(f'const Map<String, int> segoe{name.capitalize()}Kerning = {{')
        items = sorted(t.items())
        row = []
        for k, v in items:
            row.append(f'{dart_str(k)}: {v}')
            if len(row) == 5:
                lines.append('  ' + ', '.join(row) + ',')
                row = []
        if row:
            lines.append('  ' + ', '.join(row) + ',')
        lines.append('};')
        lines.append('')
        print(name, len(t))
    open(out_path, 'w', encoding='utf-8', newline='').write('\n'.join(lines))


main()
